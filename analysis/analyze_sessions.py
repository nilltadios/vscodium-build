#!/usr/bin/env python3
"""Split each past version-update session's wall-clock time into model, tool and user-wait time.

Usage (from the repository root):
    uv run analysis/analyze_sessions.py > analysis/session-breakdown.md

Inputs: Claude Code transcripts in ~/.claude/projects/-home-nilllinux22-Documents-VSCodium-Build/*.jsonl
(the sessions listed in SESSIONS below). Every interval between two consecutive transcript events is
attributed to the event that ends it: a tool result -> tool time, an assistant block -> model time,
a human prompt -> waiting on the user. The intervals partition the session, so the three totals add up
to the session's elapsed time.
"""
import json
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

PROJECT = Path.home() / ".claude/projects/-home-nilllinux22-Documents-VSCodium-Build"
SESSIONS = {
    "1.141.0": "cca6dddc-d1c2-4c7a-b26c-a81790b5173b",
    "1.141.2": "14d3daa4-22c1-4852-b576-c5c06a67b3dc",
    "1.142.0": "abae530d-b2c5-4e9a-b5d3-e44015817aba",
}


def ts(record):
    return datetime.fromisoformat(record["timestamp"].replace("Z", "+00:00"))


def is_human(record):
    if record.get("type") != "user":
        return False
    content = record.get("message", {}).get("content")
    if isinstance(content, list) and any(c.get("type") == "tool_result" for c in content):
        return False
    return record.get("origin", {}).get("kind") == "human" or record.get("turnOrigin") == "human"


def analyze(version, session_id):
    records = []
    for line in (PROJECT / f"{session_id}.jsonl").read_text().splitlines():
        r = json.loads(line)
        if "timestamp" in r and r.get("type") in ("user", "assistant") and not r.get("isSidechain"):
            records.append(r)
    records.sort(key=ts)

    tool_inputs = {}
    usage = {}
    tool_names = Counter()
    for r in records:
        if r["type"] == "assistant":
            msg = r["message"]
            usage[msg.get("id")] = msg.get("usage", {})
            for c in msg.get("content", []):
                if c.get("type") == "tool_use":
                    tool_inputs[c["id"]] = (c["name"], c.get("input", {}))
                    tool_names[c["name"]] += 1

    totals = Counter()
    tool_spans, model_spans, user_spans = [], [], []
    prompts = 0
    prev = None
    for r in records:
        if prev is not None:
            dt = (ts(r) - ts(prev)).total_seconds()
            if is_human(r):
                totals["user"] += dt
                user_spans.append((dt, ts(prev)))
            elif r["type"] == "user" and not isinstance(r["message"].get("content"), list):
                totals["other"] += dt  # injected non-human message (task notification, hook output)
            elif r["type"] == "user":  # tool result
                totals["tool"] += dt
                ids = [c.get("tool_use_id") for c in r["message"]["content"]
                       if isinstance(c, dict) and c.get("type") == "tool_result"]
                name, inp = tool_inputs.get(ids[0], ("?", {})) if ids else ("?", {})
                label = inp.get("description") or inp.get("command") or inp.get("file_path") or ""
                tool_spans.append((dt, name, str(label).replace("\n", " ")[:90]))
            else:
                totals["model"] += dt
                model_spans.append((dt, ts(prev)))
        if is_human(r):
            prompts += 1
        prev = r

    elapsed = (ts(records[-1]) - ts(records[0])).total_seconds()
    out_tokens = sum(u.get("output_tokens", 0) for u in usage.values())
    think_tokens = sum(u.get("output_tokens_details", {}).get("thinking_tokens", 0) for u in usage.values())
    return dict(version=version, session=session_id, start=ts(records[0]), end=ts(records[-1]),
                elapsed=elapsed, totals=totals, prompts=prompts, turns=len(usage),
                out_tokens=out_tokens, think_tokens=think_tokens, tool_names=tool_names,
                tool_spans=sorted(tool_spans, reverse=True), model_spans=sorted(model_spans, reverse=True),
                user_spans=sorted(user_spans, reverse=True))


def minutes(s):
    return f"{s / 60:.1f}"


def main():
    results = [analyze(v, s) for v, s in SESSIONS.items()]
    w = sys.stdout.write
    w("# Version-update sessions: where the wall-clock went\n\n")
    w("Generated by `uv run analysis/analyze_sessions.py`. Minutes; model = time the agent spent generating "
      "(including thinking) between events, tool = time waiting for commands, user = idle until the next human prompt.\n\n")
    w("| Version | Start (UTC) | Elapsed | Model | Tool | User wait | Other | Prompts | API calls | Output tok | Thinking tok |\n")
    w("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n")
    for r in results:
        t = r["totals"]
        w(f"| {r['version']} | {r['start']:%Y-%m-%d %H:%M} | {minutes(r['elapsed'])} | {minutes(t['model'])} | "
          f"{minutes(t['tool'])} | {minutes(t['user'])} | {minutes(t['other'])} | {r['prompts']} | {r['turns']} | {r['out_tokens']:,} | "
          f"{r['think_tokens']:,} |\n")
    for r in results:
        w(f"\n## {r['version']} (`{r['session']}`)\n\n")
        w("Tool calls: " + ", ".join(f"{n} {k}" for k, n in r["tool_names"].most_common()) + "\n\n")
        w("Longest tool waits:\n\n| Seconds | Tool | Description |\n| ---: | --- | --- |\n")
        for dt, name, label in r["tool_spans"][:10]:
            w(f"| {dt:.0f} | {name} | {label.replace('|', '/')} |\n")
        long_model = [d for d, _ in r["model_spans"] if d >= 60]
        w(f"\nModel spans >= 60 s: {len(long_model)}, totalling {minutes(sum(long_model))} min "
          f"(longest {max(long_model, default=0):.0f} s).\n")
        w("Longest model spans (s, starting UTC): " +
          ", ".join(f"{d:.0f} @ {t:%H:%M:%S}" for d, t in r["model_spans"][:8]) + "\n")
        w("User waits >= 60 s (s, starting UTC): " +
          (", ".join(f"{d:.0f} @ {t:%H:%M}" for d, t in r["user_spans"] if d >= 60) or "none") + "\n")


if __name__ == "__main__":
    main()
